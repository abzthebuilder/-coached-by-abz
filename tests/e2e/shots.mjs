import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium, devices } = require("playwright");
const base = process.env.BASE_URL || "http://localhost:3000";
const out = process.argv[2] || "screenshots";
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 13"] });
const page = await ctx.newPage();
const shot = async (name, full = true) => page.screenshot({ path: `${out}/${name}.png`, fullPage: full });
await page.goto(base + "/"); await shot("01-home");
await page.goto(base + "/login");
await page.fill('input[name=email]', "alex@demo.coachedbyabz.com");
await page.fill('input[name=password]', "alex-demo-pass-1");
await page.click('button[type=submit]');
await page.waitForURL("**/app");
await shot("02-today");
await page.goto(base + "/app/progress");
const svg = page.locator("svg[role=img][tabindex='0']"); const b = await svg.boundingBox();
await page.mouse.click(b.x + b.width * 0.7, b.y + b.height / 2); await shot("03-progress");
await page.goto(base + "/app/training"); await shot("04-training", false);
const c2 = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const p2 = await c2.newPage();
await p2.goto(base + "/login");
await p2.fill('input[name=email]', "coach@demo.coachedbyabz.com");
await p2.fill('input[name=password]', "coach-demo-pass-1");
await p2.click('button[type=submit]');
await p2.waitForURL("**/coach");
await p2.screenshot({ path: `${out}/05-coach.png` });
await p2.click("text=Alex Turner");
await p2.waitForLoadState("networkidle");
await p2.screenshot({ path: `${out}/06-coach-client.png`, fullPage: true });
await browser.close();
